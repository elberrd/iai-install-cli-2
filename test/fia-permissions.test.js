test('enforce: protected imp/ paths always blocked', () => {
  const root = mkdtempSync(join(tmpdir(), 'fia-perm-'));
  initGitRepo(root);
  mkdirSync(join(root, 'imp', 'modules'), { recursive: true });
  writeFileSync(join(root, 'imp', 'modules', 'runner.mjs'), '// protected\n');
  execFileSync('git', ['add', 'imp'], { cwd: root, stdio: 'ignore' });
  execFileSync('git', ['commit', '-m', 'add imp'], { cwd: root, stdio: 'ignore' });
  const run = {
    repoRoot: root,
    cfg: { defaults: { protected_files: ['imp/modules/'] } },
  };
  const before = snapshot(run);
  writeFileSync(join(root, 'imp', 'modules', 'runner.mjs'), '// tampered\n');
  assert.throws(
    () => enforce(run, {}, { name: 'builder', writes: ['**/*'] }, before),
    PermissionBreach,
  );
  // Rollback: the protected file was restored from HEAD.
  assert.equal(readFileSync(join(root, 'imp', 'modules', 'runner.mjs'), 'utf8'), '// protected\n');
});
