/**
 * Playwright bootstrap and deterministic e2e execution for fda_qa.mjs.
 * Known commands stay in code phases — never delegated to an agent.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { execFileSync, spawn } from 'node:child_process';
import { nowIso } from './utils.mjs';

const PLAYWRIGHT_CONFIG = 'playwright.config.ts';

export function readPackageScripts(repoRoot) {
  try {
    return JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')).scripts || {};
  } catch {
    return {};
  }
}

export function hasPlaywrightDep(repoRoot) {
  try {
    const pkg = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    return Boolean(deps['@playwright/test']);
  } catch {
    return false;
  }
}

